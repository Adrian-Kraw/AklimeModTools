local C = AklimeMod_Colorizer
if not C then return end

local function Translate(entry)
    if type(entry) == "table" and entry.label then
        entry.label = DE[entry.label] or entry.label
    end
end

for _, skin in pairs(C.skins) do
    Translate(skin)
    for _, color in pairs(skin.colors or {}) do Translate(color) end
    for _, toggle in pairs(skin.toggles or {}) do Translate(toggle) end
end
for _, group in ipairs(C.groupOrder) do Translate(group) end
